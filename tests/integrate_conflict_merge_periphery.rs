//! Periphery (real-on-disk-config, real-git, cross-module) tests for spec 88, criterion 1
//! (INTEGRATE-CONFLICT MERGES): a unit whose integration hits a merge conflict is re-parked
//! with the run branch merged INTO its worktree instead of being reset off it, and a conflict
//! confined to a registered `regenerate:` path resolves itself with no spawn.
//!
//! WHAT THE IMPLEMENTER'S OWN TESTS ALREADY COVER (not re-proven here). `src/worktree.rs`'s
//! own `mod tests` proves `Worktree::integrate`'s merge-direction flip directly:
//! `conflicting_paths`/`merge_in_progress` read real worktree state, a conflict leaves markers
//! in place with the unit branch untouched, and a crash-resumed re-entry is idempotent.
//! `src/conductor.rs`'s own `mod tests` drives `run()` end to end with a fake `AgentDriver`
//! for three shapes: a plain re-park that resolves and both units land with no attempt
//! charged, a conflict CONFINED ENTIRELY to a registered regenerable path resolving with no
//! spawn at all, and the `CONFLICT_RESOLVE_BOUND`-exhausted fallback charging a real attempt
//! with cause `"integrate-conflict"`. None of that is re-derived here.
//!
//! WHAT THIS FILE OWNS - four gaps those inside-out layers are structurally blind to, found
//! by re-reading the diff against `git merge-base HEAD rigger-run` rather than by inspection
//! alone (recorded as `sdet-u88c1-boundary-accounting` and, for GAP 4, added on round 1's own
//! diff as `sdet-u88c1r1-boundary-accounting` / `sdet-u88c1r1-gap4-added-and-verified`).
//!
//! GAP 1, `regenerate_config_round_trips_through_the_real_on_disk_loader_with_back_compat`. The
//! implementer's own tests build `cfg.workflow.regenerate` via Rust struct literals; none of
//! them ever parse a real `regenerate:` YAML block through `config::load` (the actual
//! `serde(Deserialize)` surface a hand-authored `.rigger/workflow.yml` exercises). This drives
//! the real on-disk loader for a multi-rule, multi-path block, for the back-compat case (an
//! omitted key - every workflow.yml committed before this criterion existed - must resolve to
//! an empty list, not an error), and for the REAL, currently-committed project
//! `.rigger/workflow.yml` itself, pinning its own `docs/audit/*` rule.
//!
//! GAP 2,
//! `a_mixed_source_and_regenerable_conflict_resolves_the_source_first_then_regenerates_for_real`.
//! The Design's own CONSTRAINTS WALK names a conflict spanning BOTH a source file and a
//! registered regenerable path ("the artifact is regenerated by the conductor after the
//! implementer resolves the source conflict, in that order"), and the production code has a
//! whole branch dedicated to it (`Worktree::accept_incoming`, `resolve_integrate_conflict`'s
//! `regenerable`/`source` partition with `regenerable` non-empty AND `source` non-empty). Every
//! one of the implementer's three new conductor tests conflicts on exactly one file, entirely
//! source or entirely regenerable - the MIXED branch has zero coverage anywhere in the diff.
//! This drives it across TWO real retries (round 1 review, adv-u88c1-mixed-conflict-regen-
//! skipped-on-multiretry: a single-retry drive left the multi-retry accumulation bug - the
//! `regenerable` path staged on retry 1 losing itself out of `resolve_integrate_conflict`'s
//! per-iteration partition by the time retry 2 finally clears the tree - entirely uncaught) and
//! proves the re-park's `blast_radius` names only the source path on every retry, the
//! regenerable path is placeholder-resolved just enough to unblock the commit, and the FINAL
//! landed content is the real regenerated output (not the incoming placeholder silently
//! standing in for it forever, which is exactly what a retry-1-then-done drive cannot observe).
//!
//! GAP 3, `a_post_merge_red_rollback_resets_the_units_own_branch_not_just_the_repo`. This
//! diff's OWN new code comment states the failure mode precisely: "its NEXT attempt would
//! fast-forward the repo from a branch still carrying the abandoned merge commit, silently
//! erasing whatever the repo held." The pre-existing spec-12-unit-5 `MergeBreakDriver` test
//! (unmodified by this diff, only cross-referenced from a doc comment) asserts the REPO's tree
//! and the recorded cause, but never once inspects the LOSING unit's OWN branch ref - so it
//! cannot see whether `unit_head_before_merge`'s reset actually fires. This drives the identical
//! clean-merge-then-red-postmerge-gate scenario and inspects the loser's own worktree at its
//! retry spawn: the branch there must be a single-parent commit (the abandoned two-parent merge
//! commit discarded) carrying exactly the loser's own prior work (not over-corrected back to
//! the shared base either).
//!
//! GAP 4 (round 1 review fix), `regenerate_conflicted_paths_runs_through_the_injected_gates_
//! port_not_a_raw_shell_out`. Round 1 fixed `run_regenerate_command` to call the injected
//! `gate::Runner` port (`Deps.gates`) instead of a raw, un-injected `std::process::Command`
//! shell-out (arch-u88c1-regenerate-bypasses-runner-port-and-build-budget) - but every existing
//! test that exercises regeneration, this file's own GAP 2 included, wires `Deps.gates` to the
//! REAL `ExecRunner`, which runs the registered command as a real shell either way and so cannot
//! tell the two implementations apart. This drives the confined-to-regenerable scenario with a
//! fake `Runner` that intercepts only the `"regenerate"` gate id and proves BOTH that the port is
//! actually called (with the exact gate id/command/dir) and that the port's own output - not a
//! parallel raw shell-out's - is what lands.

