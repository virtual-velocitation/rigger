/// Write a minimal but real `.rigger/agents/worker.md` + `.rigger/workflow.yml` at `root`, so
/// `config::load` reaches all the way through agent parsing and `Config::validate` - the real
/// on-disk boundary, not a struct literal built in memory. Mirrors
/// `tests/build_budget_slots_periphery.rs::write_workflow`'s identical technique for
/// `build.max_concurrent` (spec 65), now for `regenerate:` (spec 88, criterion 1).
/// `regenerate_block` is appended verbatim: `""` omits the section entirely (the back-compat
/// case).
fn write_workflow(root: &Path, regenerate_block: &str) {
    let rigger = root.join(".rigger");
    std::fs::create_dir_all(rigger.join("agents")).expect("create .rigger/agents");
    std::fs::write(
        rigger.join("agents").join("worker.md"),
        "---\nid: worker\nmodel: sonnet\ntools: [Read, Edit]\nisolation: none\n---\nDo the unit.\n",
    )
    .expect("write worker.md");
    let workflow = format!(
        "name: regeneratetest\n\
         defaults:\n  grounder: nop\n  budget: 60\n\
         stages:\n  a:\n    agent: worker\n    on_pass: none\n\
         {regenerate_block}"
    );
    std::fs::write(rigger.join("workflow.yml"), workflow).expect("write workflow.yml");
}

#[test]
fn regenerate_config_round_trips_through_the_real_on_disk_loader_with_back_compat() {
    // (a) a real regenerate: block, TWO rules, the first with TWO paths - proves the YAML
    // shape (a list of {paths: [...], run: ...} maps) round-trips field-for-field through
    // the real serde(Deserialize) surface, not just that SOME shape parses.
    let configured = tempfile::tempdir().expect("create temp project");
    write_workflow(
        configured.path(),
        "regenerate:\n\
         - paths: [\"docs/audit/*\", \"docs/other/*\"]\n\
         \u{20}\u{20}run: \"echo one\"\n\
         - paths: [\"gen/*.json\"]\n\
         \u{20}\u{20}run: \"echo two\"\n",
    );
    let cfg = config::load(configured.path().to_str().unwrap()).expect("load a valid workflow.yml");
    assert_eq!(
        cfg.workflow.regenerate.len(),
        2,
        "both rules must round-trip: {:?}",
        cfg.workflow.regenerate
    );
    assert_eq!(
        cfg.workflow.regenerate[0].paths,
        vec!["docs/audit/*".to_string(), "docs/other/*".to_string()]
    );
    assert_eq!(cfg.workflow.regenerate[0].run, "echo one");
    assert_eq!(
        cfg.workflow.regenerate[1].paths,
        vec!["gen/*.json".to_string()]
    );
    assert_eq!(cfg.workflow.regenerate[1].run, "echo two");

    // (b) the back-compat case: an OMITTED regenerate: key - every workflow.yml committed
    // before this criterion existed - must still load cleanly through the real loader and
    // resolve to an EMPTY list (every conflict re-parks the implementer exactly as it would
    // otherwise, per Workflow::regenerate's own doc comment), never an error and never a
    // silently-defaulted rule.
    let legacy = tempfile::tempdir().expect("create temp project");
    write_workflow(legacy.path(), "");
    let cfg = config::load(legacy.path().to_str().unwrap())
        .expect("a workflow.yml with no regenerate: section must still load");
    assert!(
        cfg.workflow.regenerate.is_empty(),
        "an omitted regenerate: section must resolve to an empty list through the real loader; \
         got {:?}",
        cfg.workflow.regenerate
    );

    // (c) the REAL, currently-committed project workflow.yml - not a synthetic fixture. It
    // must load through the exact same `config::load` path `main.rs` uses in production, and
    // its own registered rule (this diff's own worked example) must be exactly what the
    // committed file states: `docs/audit/*` regenerated via the simplification_audit test.
    let project_root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let real_cfg = config::load(project_root.to_str().unwrap())
        .expect("the project's own .rigger/workflow.yml must load through the real loader");
    assert!(
        real_cfg
            .workflow
            .regenerate
            .iter()
            .any(|r| r.paths == vec!["docs/audit/*".to_string()]
                && r.run.contains("simplification_audit")),
        "the real committed workflow.yml must register docs/audit/* as regenerable via the \
         simplification_audit regeneration command; got: {:?}",
        real_cfg.workflow.regenerate
    );
}

