const MB_BASE: &str = "unrelated line one\nunrelated line two\n";

/// Drives the identical clean-merge-then-red-postmerge-gate scenario the pre-existing
/// `MergeBreakDriver` (spec 12, unit 5) proves lands correctly on the REPO - `unit-a` prepends a
/// mark, `unit-b` appends one off the same base; both gate green alone, the merge auto-succeeds
/// (non-overlapping regions), but the merged tree carries two marks and the post-merge gate
/// rejects it. WHICH of the two loses the integrate-lock race (and so hits the post-merge-red
/// block) is a genuine race MergeBreakDriver itself never pins either - so, unlike that driver,
/// BOTH units here behave identically and symmetrically per attempt: attempt 0 reproduces the
/// break (prepend for a, append for b - so the loser's merge auto-succeeds without a raw
/// conflict), any later attempt - BEFORE writing anything - snapshots the worktree's CURRENT
/// branch state (the thing this test actually pins: a single-parent commit carrying the loser's
/// own prior work, or the abandoned two-parent merge commit the reset should have discarded)
/// and then writes NEUTRAL content (reverts its own side to unchanged base) so the retry's merge
/// carries only the winner's one mark and gates green.
struct BranchResetDriver {
    repo: String,
    /// One entry per unit whose implementer ran at `attempt > 0`: `(parent count, m.rs content)`
    /// of its worktree HEAD, captured before this driver wrote anything that attempt - i.e. the
    /// state the conductor's post-merge-red rollback left it in. Whichever of unit-a/unit-b
    /// loses the race gets exactly one entry here; the winner (never blocked, never retried)
    /// gets none.
    retry_snapshots: Mutex<std::collections::HashMap<String, (usize, String)>>,
}

impl AgentDriver for BranchResetDriver {
    fn spawn(
        &self,
        _a: &AgentDef,
        _prompt: &str,
        opts: &SpawnOpts,
        _emit: &dyn Fn(&str, Value) -> Result<(), Error>,
    ) -> Result<AgentResult, Error> {
        let unit = opts.id.split('/').next().unwrap_or_default().to_string();
        if opts.id.contains("/implementer#") {
            if !opts.dir.is_empty() {
                if opts.attempt == 0 {
                    for _ in 0..400 {
                        let n = Command::new("git")
                            .arg("-C")
                            .arg(&self.repo)
                            .args(["branch", "--list", "rigger/u/*"])
                            .output()
                            .map(|o| String::from_utf8_lossy(&o.stdout).lines().count())
                            .unwrap_or(0);
                        if n >= 2 {
                            break;
                        }
                        std::thread::sleep(std::time::Duration::from_millis(25));
                    }
                    // Reproduces the break: each unit adds its OWN mark in a DIFFERENT,
                    // non-overlapping region (prepend for a, append for b), same as
                    // MergeBreakDriver - whichever one integrates second merges cleanly into a
                    // tree that already carries the other's mark, producing two.
                    let content = if unit == "unit-a" {
                        format!("MARK\n{MB_BASE}")
                    } else {
                        format!("{MB_BASE}MARK\n")
                    };
                    std::fs::write(Path::new(&opts.dir).join("m.rs"), content).unwrap();
                } else {
                    // The retry: snapshot BEFORE writing anything - this is the state the
                    // conductor's post-merge-red rollback left the worktree in.
                    let head = git_out(&opts.dir, &["rev-parse", "HEAD"]);
                    let parents = git_out(&opts.dir, &["log", "-1", "--format=%P", &head]);
                    let parent_count = if parents.trim().is_empty() {
                        0
                    } else {
                        parents.split_whitespace().count()
                    };
                    let content =
                        std::fs::read_to_string(Path::new(&opts.dir).join("m.rs")).unwrap();
                    self.retry_snapshots
                        .lock()
                        .unwrap()
                        .insert(unit, (parent_count, content));
                    // The real fix: contribute NOTHING further to the shared region - this
                    // unit's own portion reverts to unchanged base, so the merged tree carries
                    // only the other unit's one mark and the post-merge gate goes green.
                    std::fs::write(Path::new(&opts.dir).join("m.rs"), MB_BASE).unwrap();
                }
            }
            return Ok(AgentResult::default());
        }
        Ok(review_or_adjudicate(opts))
    }
}

#[test]
fn a_post_merge_red_rollback_resets_the_units_own_branch_not_just_the_repo() {
    let repo = init_repo();
    let repo_path = repo.path().to_str().unwrap().to_string();
    std::fs::write(Path::new(&repo_path).join("m.rs"), MB_BASE).unwrap();
    git_commit_all(&repo_path, "base m.rs");

    let store = Store::open(":memory:").unwrap();
    let driver = BranchResetDriver {
        repo: repo_path.clone(),
        retry_snapshots: Mutex::new(std::collections::HashMap::new()),
    };

    let mut cfg = Config::default();
    // whichever unit loses the integrate-lock race must survive its FIRST block and get a
    // real second attempt: at least 2.
    cfg.workflow.defaults.max_retries = 2;
    cfg.agents.insert("worker".into(), agent("worker"));
    cfg.agents.insert("lens".into(), agent("lens"));
    cfg.agents.insert("judge".into(), agent("judge"));
    cfg.workflow.gates.insert(
        "g".into(),
        gate_def(
            "c=$(grep -c MARK m.rs 2>/dev/null); c=${c:-0}; \
             if [ \"$c\" -le 1 ]; then exit 0; else \
             echo 'gate g failed: merge introduced duplicate MARK'; exit 1; fi",
        ),
    );
    cfg.workflow
        .stages
        .insert("unit-a".into(), mk_stage("unit-a", "g"));
    cfg.workflow
        .stages
        .insert("unit-b".into(), mk_stage("unit-b", "g"));

    let deps = Deps {
        store: &store,
        driver: &driver,
        gates: &rigger::gate::ExecRunner,
        repo: repo_path.clone(),
        grounder: None,
        graph: None,
        criteria: Vec::new(),
    };
    let rs = run(&cfg, &deps).unwrap();

    // Both units integrate: the winner cleanly, the loser (whichever one lost the
    // integrate-lock race - a genuine race MergeBreakDriver itself never pins either) after
    // its rollback-and-retry recovers.
    assert_eq!(rs.units["unit-a"].status, ledger::Status::Integrated);
    assert_eq!(
        rs.units["unit-b"].status,
        ledger::Status::Integrated,
        "both units must land, or this test proves nothing about the retry state"
    );

    // Exactly one of the two took a retry (the loser); the winner never blocked.
    let snapshots = driver.retry_snapshots.lock().unwrap();
    assert_eq!(
        snapshots.len(),
        1,
        "exactly one unit (the loser of the integrate-lock race) must have retried; got {:?}",
        snapshots.keys().collect::<Vec<_>>()
    );
    let (loser, (parent_count, content)) = snapshots.iter().next().unwrap();
    let own_mark = if loser == "unit-a" {
        format!("MARK\n{MB_BASE}")
    } else {
        format!("{MB_BASE}MARK\n")
    };

    // The actual claim: at the retry, the loser's worktree HEAD was a SINGLE-parent commit
    // (the abandoned two-parent auto-merge commit was discarded by the branch reset, not just
    // the repo) carrying EXACTLY the loser's own prior work - not the base content either
    // (which would mean the reset over-corrected and threw away its real, reviewed work too).
    assert_eq!(
        *parent_count, 1,
        "{loser}'s own branch must be reset to its single-parent pre-merge commit, not left \
         carrying the abandoned two-parent merge commit the post-merge-red rollback discarded \
         on the repo side"
    );
    assert_eq!(
        *content, own_mark,
        "the reset must land on EXACTLY {loser}'s own prior work (its one-mark commit), \
         neither the abandoned merge commit's two-mark content nor an over-corrected reset all \
         the way back to the shared base"
    );

    // The merged tree carries exactly one mark (the winner's); the broken two-mark tree from
    // the loser's first attempt never landed.
    let merged = std::fs::read_to_string(Path::new(&repo_path).join("m.rs")).unwrap();
    assert_eq!(
        merged.matches("MARK").count(),
        1,
        "the run branch holds only the winner's one mark: {merged}"
    );

    // The block that triggered the rollback is stamped "integrate-conflict" (spec 69's cause
    // wire), same as the pre-existing MergeBreakDriver test - reused here as a sanity check,
    // not re-derived.
    let events = store.read_stream(STREAM, 0, Direction::Forward).unwrap();
    let cause = events
        .iter()
        .find(|e| {
            e.type_ == ledger::TYPE_UNIT_FAILED
                && String::from_utf8_lossy(&e.data).contains(&format!("\"id\":\"{loser}\""))
        })
        .map(|e| serde_json::from_slice::<Value>(&e.data).unwrap()["cause"].clone());
    assert_eq!(cause, Some(Value::String("integrate-conflict".into())));
    drop(repo);
}

